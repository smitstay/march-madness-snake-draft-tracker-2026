import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const browser = await chromium.launch({headless:true, args:['--no-sandbox']});
try {
  const context = await browser.newContext({httpCredentials:{username:'test', password:process.env.EDGE_TEST_PASSWORD}, viewport:{width:1440,height:1000}});
  const page=await context.newPage();
  const errors=[];page.on('pageerror', e=>errors.push(String(e)));
  await page.goto(`${process.env.EDGE_TEST_URL}/edge/`);
  await page.getByRole('heading',{name:'Draft Lab / March'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Pick',exact:true}).count(),64);
  await page.getByRole('button',{name:'Pick',exact:true}).first().click();
  assert.equal(await page.getByRole('button',{name:'Pick',exact:true}).count(),63);
  await page.reload();
  assert.equal(await page.getByRole('button',{name:'Pick',exact:true}).count(),63);
  await page.getByRole('button',{name:'Undo pick'}).click();
  assert.equal(await page.getByRole('button',{name:'Pick',exact:true}).count(),64);
  await page.getByLabel('My draft seat').selectOption('0');
  assert.match(await page.locator('.stats').innerText(),/YOUR TURN/);
  await page.getByLabel('Rank by').selectOption('win');
  assert.match(await page.locator('tbody tr').first().innerText(),/%/);
  await page.getByRole('button',{name:'Pick',exact:true}).first().click();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export draft'}).click();
  const download=await downloadPromise; const path=await download.path();
  const data=JSON.parse(await fs.readFile(path,'utf8'));assert.equal(data.teamIds.length,1);
  await page.getByRole('button',{name:'Undo pick'}).click();
  await page.getByLabel('Restore exported draft').setInputFiles(path);
  await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 63);
  assert.equal(await page.getByRole('button',{name:'Pick',exact:true}).count(),63);
  await page.getByLabel('Import forecast JSON').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{}')});
  await page.getByRole('alert').waitFor();
  assert.equal(await page.getByRole('button',{name:'Pick',exact:true}).count(),63);
  await page.getByRole('button',{name:'Historical evidence'}).click();
  await page.getByRole('heading',{name:'Test the edge, don’t assume it'}).waitFor();
  await page.getByRole('button',{name:'Strategy & data'}).click();
  await page.getByRole('heading',{name:'Draft wins, not just a champion'}).waitFor();
  await page.getByRole('button',{name:'Draft room'}).click();
  await page.screenshot({path:'/tmp/ncaa-edge-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/tmp/ncaa-edge-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth));
  assert.deepEqual(errors,[]);
  console.log('PASS: browser desktop/mobile rendering, picks, undo, persistence, win-share sorting, export/restore, invalid import, evidence tabs, no uncaught errors.');
} finally {await browser.close();}
